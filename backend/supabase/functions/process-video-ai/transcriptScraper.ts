// Deno-compatible Multi-Language Transcript Scraper for YouTube & Social Media
// Scrapes free public subtitles/timedtext using both Desktop and InnerTube Android API fallback.

export interface TranscriptSnippet {
  text: string;
  start: number; // in seconds
  duration: number; // in seconds
}

export interface TranscriptResult {
  snippets: TranscriptSnippet[];
  fullText: string;
  language: string;
  isAutoGenerated: boolean;
}

/**
 * Extracts YouTube video ID from standard, shorts, or mobile URLs
 */
export function extractYouTubeId(url: string): string | null {
  if (!url) return null;
  const regExp =
    /(?:youtu\.be\/|youtube\.com\/(?:embed\/|v\/|watch\?v=|watch\?.+&v=|shorts\/|live\/))([\w-]{11})/;
  const match = url.match(regExp);
  return match ? match[1] : null;
}

/**
 * Robust YouTube caption fetcher:
 * 1. Tries desktop webpage player response
 * 2. Falls back to YouTube InnerTube API (Android client) which bypasses web bot consent blocks
 * 3. Supports English, Hindi, Urdu, Spanish, and any available auto-caption track
 */
export async function fetchYouTubeTranscript(
  videoId: string,
  preferredLanguages: string[] = ["en", "hi", "ur", "es"],
): Promise<TranscriptResult> {
  const emptyResult: TranscriptResult = {
    snippets: [],
    fullText: "",
    language: "unknown",
    isAutoGenerated: false,
  };

  try {
    let captionTracks: any[] = [];

    // Attempt 1: Fetch YouTube video page HTML
    try {
      const videoPageResponse = await fetch(
        `https://www.youtube.com/watch?v=${videoId}`,
        {
          headers: {
            "User-Agent":
              "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/124.0.0.0 Safari/537.36",
            "Accept-Language": "en-US,en;q=0.9,hi;q=0.8,ur;q=0.7",
          },
          signal: AbortSignal.timeout(6000),
        },
      );

      if (videoPageResponse.ok) {
        const html = await videoPageResponse.text();

        // Check for captionTracks in html
        const captionsMatch = html.match(/"captionTracks":\s*(\[.*?\])/);
        if (captionsMatch && captionsMatch[1]) {
          try {
            captionTracks = JSON.parse(captionsMatch[1]);
          } catch {
            // parse error
          }
        }
      }
    } catch (e) {
      console.warn("[transcriptScraper] Desktop HTML fetch failed:", e);
    }

    // Attempt 2: InnerTube Android API fallback (high reliability, no web consent wall)
    if (!Array.isArray(captionTracks) || captionTracks.length === 0) {
      try {
        const innerTubeResponse = await fetch(
          "https://www.youtube.com/youtubei/v1/player",
          {
            method: "POST",
            headers: {
              "Content-Type": "application/json",
              "User-Agent":
                "com.google.android.youtube/19.09.37 (Linux; U; Android 14) gzip",
            },
            body: JSON.stringify({
              videoId,
              context: {
                client: {
                  clientName: "ANDROID",
                  clientVersion: "19.09.37",
                  hl: "en",
                  gl: "US",
                },
              },
            }),
            signal: AbortSignal.timeout(6000),
          },
        );

        if (innerTubeResponse.ok) {
          const data = await innerTubeResponse.json();
          const tracks =
            data?.captions?.playerCaptionsTracklistRenderer?.captionTracks;
          if (Array.isArray(tracks) && tracks.length > 0) {
            captionTracks = tracks;
          }
        }
      } catch (e) {
        console.warn("[transcriptScraper] InnerTube API fallback error:", e);
      }
    }

    if (!Array.isArray(captionTracks) || captionTracks.length === 0) {
      return emptyResult;
    }

    // Prioritize preferred languages (manual tracks first, then auto-generated ASR)
    let selectedTrack: any = null;

    // Check for manual tracks in preferred languages
    for (const lang of preferredLanguages) {
      selectedTrack = captionTracks.find(
        (t: any) =>
          (t.languageCode === lang || t.languageCode?.startsWith(lang)) &&
          t.kind !== "asr",
      );
      if (selectedTrack) break;
    }

    // If no manual track found, check for auto-generated ASR tracks in preferred languages
    if (!selectedTrack) {
      for (const lang of preferredLanguages) {
        selectedTrack = captionTracks.find(
          (t: any) =>
            t.languageCode === lang || t.languageCode?.startsWith(lang),
        );
        if (selectedTrack) break;
      }
    }

    // Otherwise, pick the very first available caption track
    if (!selectedTrack) {
      selectedTrack = captionTracks[0];
    }

    if (!selectedTrack || !selectedTrack.baseUrl) {
      return emptyResult;
    }

    // Fetch timedtext XML from YouTube
    const transcriptXmlResponse = await fetch(selectedTrack.baseUrl, {
      signal: AbortSignal.timeout(6000),
    });
    if (!transcriptXmlResponse.ok) {
      return emptyResult;
    }

    const xmlText = await transcriptXmlResponse.text();

    // Parse simple XML timedtext nodes: <text start="0.5" dur="3.2">Hello world</text>
    const snippets: TranscriptSnippet[] = [];
    const textNodeRegex =
      /<text\s+start="([\d.]+)"(?:\s+dur="([\d.]+)")?[^>]*>([\s\S]*?)<\/text>/g;
    let match: RegExpExecArray | null;

    while ((match = textNodeRegex.exec(xmlText)) !== null) {
      const start = parseFloat(match[1]) || 0;
      const duration = parseFloat(match[2]) || 2;
      // Decode XML entities (e.g. &amp;, &quot;, &#39;)
      let text = match[3]
        .replace(/&amp;/g, "&")
        .replace(/&lt;/g, "<")
        .replace(/&gt;/g, ">")
        .replace(/&quot;/g, '"')
        .replace(/&#39;/g, "'")
        .replace(/&#x27;/g, "'")
        .replace(/\n/g, " ")
        .trim();

      if (text.length > 0) {
        snippets.push({ text, start, duration });
      }
    }

    const fullText = snippets.map((s) => s.text).join(" ");
    const isAuto = selectedTrack.kind === "asr" || !selectedTrack.vssId?.startsWith(".");

    return {
      snippets,
      fullText,
      language: selectedTrack.languageCode || "en",
      isAutoGenerated: isAuto,
    };
  } catch (err) {
    console.warn(
      `[transcriptScraper] Failed to fetch YouTube captions for ${videoId}:`,
      err,
    );
    return emptyResult;
  }
}

/**
 * Splits transcript snippets into coherent ~60-second chunks for pgvector embeddings
 */
export function chunkTranscript(
  snippets: TranscriptSnippet[],
  targetChunkDurationSeconds = 60,
): {
  chunkIndex: number;
  startSeconds: number;
  endSeconds: number;
  text: string;
}[] {
  if (snippets.length === 0) return [];

  const chunks: {
    chunkIndex: number;
    startSeconds: number;
    endSeconds: number;
    text: string;
  }[] = [];
  let currentTextParts: string[] = [];
  let chunkStart = snippets[0].start;
  let chunkEnd = snippets[0].start + snippets[0].duration;
  let chunkIndex = 0;

  for (const snippet of snippets) {
    currentTextParts.push(snippet.text);
    chunkEnd = snippet.start + snippet.duration;

    if (chunkEnd - chunkStart >= targetChunkDurationSeconds) {
      chunks.push({
        chunkIndex,
        startSeconds: Math.floor(chunkStart),
        endSeconds: Math.ceil(chunkEnd),
        text: currentTextParts.join(" "),
      });
      chunkIndex++;
      currentTextParts = [];
      chunkStart = snippet.start + snippet.duration;
    }
  }

  // Add trailing chunk if any
  if (currentTextParts.length > 0) {
    chunks.push({
      chunkIndex,
      startSeconds: Math.floor(chunkStart),
      endSeconds: Math.ceil(chunkEnd),
      text: currentTextParts.join(" "),
    });
  }

  return chunks;
}

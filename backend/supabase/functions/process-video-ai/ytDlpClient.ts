// Deno-compatible client for Elio AI yt-dlp Companion Microservice
// Interacts with backend/yt-dlp-service/ to provide:
// 1. Zero-video-download timed subtitle parsing for 1000+ platforms
// 2. High-speed metadata & chapter extraction
// 3. 32 kbps mono 16 kHz audio extraction safely under Whisper's 25 MB cap

import type { TranscriptSnippet } from "./transcriptScraper.ts";

export interface YtDlpMetadataResult {
  title: string;
  creator?: string;
  duration?: number;
  thumbnail?: string;
  platform?: string;
  description?: string;
  available_subtitles: string[];
  chapters: Array<{ start_time: number; end_time: number; title: string }>;
}

export interface YtDlpSubtitleResult {
  snippets: TranscriptSnippet[];
  fullTranscript: string;
  language: string;
  isAutoGenerated: boolean;
}

export interface YtDlpAudioResult {
  buffer: Uint8Array;
  fileName: string;
  durationSeconds: number;
}

/**
 * Resolves the yt-dlp service URL and authentication key from environment or defaults
 */
function getServiceConfig(): { url: string; key: string } | null {
  const url = Deno.env.get("YT_DLP_SERVICE_URL")?.trim() || "";
  if (!url) return null;
  const key = Deno.env.get("YT_DLP_SERVICE_KEY")?.trim() || "";
  return { url: url.replace(/\/+$/, ""), key };
}

/**
 * Checks if the yt-dlp companion service is configured
 */
export function isYtDlpServiceConfigured(): boolean {
  return getServiceConfig() !== null;
}

/**
 * Fetches structured subtitles/cues using the yt-dlp companion service (zero video download)
 */
export async function fetchSubtitlesViaYtDlp(
  videoUrl: string,
  preferredLanguages: string[] = ["en", "hi", "ur", "es"],
): Promise<YtDlpSubtitleResult | null> {
  const config = getServiceConfig();
  if (!config || !videoUrl) return null;

  try {
    const headers: Record<string, string> = {
      "Content-Type": "application/json",
    };
    if (config.key) {
      headers["Authorization"] = `Bearer ${config.key}`;
    }

    const res = await fetch(`${config.url}/extract-subtitles`, {
      method: "POST",
      headers,
      body: JSON.stringify({
        url: videoUrl,
        languages: preferredLanguages,
        auto_captions: true,
      }),
      signal: AbortSignal.timeout(20000), // 20s timeout
    });

    if (!res.ok) {
      console.warn(`[ytDlpClient] /extract-subtitles returned HTTP ${res.status}`);
      return null;
    }

    const data = await res.json();
    const rawSnippets = Array.isArray(data.snippets) ? data.snippets : [];

    const snippets: TranscriptSnippet[] = rawSnippets
      .map((s: any) => ({
        text: (s.text || "").trim(),
        start: parseFloat(s.start) || 0,
        duration: Math.max(parseFloat(s.duration) || 1, 1),
      }))
      .filter((s: TranscriptSnippet) => s.text.length > 0);

    if (snippets.length === 0) return null;

    const fullTranscript =
      data.full_transcript || snippets.map((s) => s.text).join(" ");

    return {
      snippets,
      fullTranscript,
      language: data.language || "en",
      isAutoGenerated: !!data.is_auto_generated,
    };
  } catch (err: any) {
    console.warn("[ytDlpClient] /extract-subtitles exception:", err.message);
    return null;
  }
}

/**
 * Extracts comprehensive video metadata and thumbnail without downloading media
 */
export async function fetchMetadataViaYtDlp(
  videoUrl: string,
): Promise<YtDlpMetadataResult | null> {
  const config = getServiceConfig();
  if (!config || !videoUrl) return null;

  try {
    const headers: Record<string, string> = {
      "Content-Type": "application/json",
    };
    if (config.key) {
      headers["Authorization"] = `Bearer ${config.key}`;
    }

    const res = await fetch(`${config.url}/extract-metadata`, {
      method: "POST",
      headers,
      body: JSON.stringify({ url: videoUrl }),
      signal: AbortSignal.timeout(15000),
    });

    if (!res.ok) return null;
    const data = await res.json();

    return {
      title: data.title || "",
      creator: data.creator || data.channel || undefined,
      duration: data.duration || undefined,
      thumbnail: data.thumbnail || undefined,
      platform: data.extractor || undefined,
      description: data.description || undefined,
      available_subtitles: Array.isArray(data.available_subtitles)
        ? data.available_subtitles
        : [],
      chapters: Array.isArray(data.chapters) ? data.chapters : [],
    };
  } catch (err: any) {
    console.warn("[ytDlpClient] /extract-metadata exception:", err.message);
    return null;
  }
}

/**
 * Extracts and downmixes audio stream (32k mono 16kHz MP3) for Whisper transcription
 */
export async function fetchAudioViaYtDlp(
  videoUrl: string,
  maxDurationSeconds: number = 3600,
): Promise<YtDlpAudioResult | null> {
  const config = getServiceConfig();
  if (!config || !videoUrl) return null;

  try {
    const headers: Record<string, string> = {
      "Content-Type": "application/json",
    };
    if (config.key) {
      headers["Authorization"] = `Bearer ${config.key}`;
    }

    const res = await fetch(`${config.url}/extract-audio`, {
      method: "POST",
      headers,
      body: JSON.stringify({
        url: videoUrl,
        format: "mp3",
        bitrate: "32k",
        channels: 1,
        sample_rate: 16000,
        return_mode: "stream",
        max_duration_seconds: maxDurationSeconds,
      }),
      signal: AbortSignal.timeout(60000), // 60s timeout for audio extraction
    });

    if (!res.ok) {
      console.warn(`[ytDlpClient] /extract-audio returned HTTP ${res.status}`);
      return null;
    }

    const arrayBuffer = await res.arrayBuffer();
    const durationSeconds = parseInt(
      res.headers.get("X-Audio-Duration") || "0",
      10,
    );

    return {
      buffer: new Uint8Array(arrayBuffer),
      fileName: "extracted_audio.mp3",
      durationSeconds,
    };
  } catch (err: any) {
    console.warn("[ytDlpClient] /extract-audio exception:", err.message);
    return null;
  }
}
